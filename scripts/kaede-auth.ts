function openBrowser(url: string): Promise<boolean> {
  const { spawn } = require('child_process');
  return new Promise((resolveOpen) => {
    let done = false;
    const finish = (ok: boolean) => {
      if (!done) { done = true; resolveOpen(ok); }
    };
    let child;
    try {
      if (process.platform === 'win32') {
        child = spawn('cmd', ['/c', 'start', '', url], { detached: true, stdio: 'ignore' });
      } else {
        const cmd = process.platform === 'darwin' ? 'open' : 'xdg-open';
        child = spawn(cmd, [url], { detached: true, stdio: 'ignore' });
      }
      child.on('error', () => finish(false));
      child.on('spawn', () => finish(true));
      setTimeout(() => finish(true), 1500);
    } catch {
      finish(false);
    }
  });
}

/**
 * Alur OAuth otomatis: ephemeral HTTP server di 127.0.0.1:<port>, buka browser
 * ke Trello dengan return_url fragment, tangkap token via POST callback.
 * Reject bila browser tak bisa dibuka atau timeout.
 */
export async function promptTokenViaLocalServer(key: string, timeoutMs = 120000): Promise<string> {
  const http = await import('node:http');
  return new Promise((resolve, reject) => {
    let settled = false;
    let timer: ReturnType<typeof setTimeout> | undefined;

    const server = http.createServer((req, res) => {
      if (req.method === 'GET' && req.url && req.url.startsWith('/callback')) {
        res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' });
        res.end(CALLBACK_HTML);
        return;
      }
      if (req.method === 'POST' && req.url === '/callback') {
        let body = '';
        req.on('data', (c: Buffer) => (body += c.toString()));
        req.on('end', () => {
          let token = '';
          try { token = (JSON.parse(body) as { token?: string }).token || ''; } catch {}
          if (token) {
            res.writeHead(200, { 'Content-Type': 'text/plain' });
            res.end('ok');
            if (!settled) { settled = true; clearTimeout(timer); server.close(() => resolve(token)); }
          } else {
            res.writeHead(400, { 'Content-Type': 'text/plain' });
            res.end('missing token');
          }
        });
        return;
      }
      res.writeHead(404, { 'Content-Type': 'text/plain' });
      res.end('not found');
    });

    server.on('error', (err: Error) => {
      if (!settled) { settled = true; clearTimeout(timer); reject(err); }
    });

    server.listen(0, '127.0.0.1', () => {
      const address = server.address() as { port: number };
      const url = buildAuthorizeUrl(key, { returnUrl: `http://127.0.0.1:${address.port}/callback` });
      console.log('  \x1b[90m  Membuka browser ke Trello untuk otorisasi...\x1b[0m');
      console.log('  \x1b[90m  URL: \x1b[0m' + url);
      console.log('');
      openBrowser(url).then((opened) => {
        if (!opened && !settled) {
          settled = true;
          clearTimeout(timer);
          server.close(() => reject(new Error('Browser tidak bisa dibuka. Gunakan `--manual`.')));
        }
      });
    });

    timer = setTimeout(() => {
      if (!settled) {
        settled = true;
        server.close(() => reject(new Error('Timeout menunggu OAuth callback (120s). Gunakan `--manual`.')));
      }
    }, timeoutMs);
  });
}
