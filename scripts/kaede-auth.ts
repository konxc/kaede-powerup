/**
 * KAEDE Auth helpers — shared by `kaede auth` command group and `kaede setup`
 * onboarding. Pure functions are exported for unit testing (test/kaede-auth.test.js).
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'fs';
import { resolve } from 'path';

export const TRELLO_API_BASE = 'https://api.trello.com/1';
export const TRELLO_AUTHORIZE_BASE = 'https://trello.com/1/authorize';

export interface Secrets {
  TRELLO_API_KEY?: string;
  TRELLO_TOKEN?: string;
  [key: string]: string | undefined;
}

export function loadEnv(filePath: string): Secrets {
  if (!existsSync(filePath)) return {};
  const content = readFileSync(filePath, 'utf-8');
  const vars: Secrets = {};
  for (const line of content.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eqIdx = trimmed.indexOf('=');
    if (eqIdx === -1) continue;
    const key = trimmed.slice(0, eqIdx).trim();
    const val = trimmed.slice(eqIdx + 1).trim();
    if (key) vars[key] = val;
  }
  return vars;
}

/** Path global ke `~/.config/kaede/secrets.env` (dasar `home`). */
export function globalSecretsPath(home: string): string {
  return resolve(home, '.config', 'kaede', 'secrets.env');
}

/**
 * Merge `partial` ke file secrets global lalu tulis ulang.
 * Nilai `undefined`/`null` berarti menghapus kunci tersebut.
 */
export function writeGlobalSecrets(home: string, partial: Partial<Secrets>): string {
  const path = globalSecretsPath(home);
  const existing = existsSync(path) ? loadEnv(path) : {};

  for (const [k, v] of Object.entries(partial)) {
    if (v === undefined || v === null) delete existing[k];
    else existing[k] = v;
  }

  const lines = [
    '# Trello API Credentials — generated by `kaede auth login`',
    '# Keep this file secret! Do NOT commit to git.',
    '',
    ...Object.entries(existing)
      .filter(([, v]) => v !== undefined && v !== '')
      .map(([k, v]) => `${k}=${v}`),
    '',
  ];

  mkdirSync(resolve(path, '..'), { recursive: true });
  writeFileSync(path, lines.join('\n'), 'utf-8');
  return path;
}

export function buildAuthorizeUrl(
  key: string,
  opts: { returnUrl?: string } = {},
): string {
  let url = `${TRELLO_AUTHORIZE_BASE}?expiration=never&name=KAEDE&scope=read,write,account&response_type=token&key=${encodeURIComponent(key)}`;
  if (opts.returnUrl) {
    url += `&return_url=${encodeURIComponent(opts.returnUrl)}&callback_method=fragment`;
  }
  return url;
}

export function maskToken(token: string): string {
  if (!token) return '';
  return token.length <= 8 ? '••••' : `${token.slice(0, 4)}…${token.slice(-4)}`;
}

export interface TokenInfo {
  id: string;
  expires: string;
  member: { id: string; fullName: string; username: string } | null;
}

/** Validasi token per-user server-side: GET /1/tokens/{token}?key= + /member. */
export async function trelloValidateToken(key: string, token: string): Promise<TokenInfo> {
  const base = `${TRELLO_API_BASE}/tokens/${encodeURIComponent(token)}`;
  const res = await fetch(`${base}?key=${encodeURIComponent(key)}`);
  if (!res.ok) {
    throw new Error(`Trello token invalid atau expired (HTTP ${res.status}). Jalankan ulang \`kaede auth login\`.`);
  }
  const data = (await res.json()) as { id?: string; dateExpires?: string | null };

  let member: TokenInfo['member'] = null;
  try {
    const memberRes = await fetch(
      `${base}/member?key=${encodeURIComponent(key)}&fields=id,fullName,username`,
    );
    if (memberRes.ok) {
      const m = (await memberRes.json()) as { id?: string; fullName?: string; username?: string };
      member = { id: m.id || '', fullName: m.fullName || '', username: m.username || '' };
    }
  } catch {}

  return {
    id: data.id || '',
    expires: data.dateExpires || 'never',
    member,
  };
}

/** Revoke token di Trello: DELETE /1/tokens/{token}?key=. */
export async function revokeToken(key: string, token: string): Promise<boolean> {
  const res = await fetch(
    `${TRELLO_API_BASE}/tokens/${encodeURIComponent(token)}?key=${encodeURIComponent(key)}`,
    { method: 'DELETE' },
  );
  return res.ok || res.status === 404;
}

